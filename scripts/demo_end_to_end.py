import os
import secrets
import sys
import uuid
from datetime import datetime, timedelta, timezone

OUTAGE_PAYMENTS = 60
OUTAGE_FAILURE_SHARE = 0.6
HEALTHY_PAYMENTS = 50
AMOUNT_MINOR_UNITS = 250000
SWITCH_AMOUNT_MINOR_UNITS = 2000  # USD 20.00
CAPTURE_DELAY_SECONDS = 30
PAYPAL_WINDOW_VOLUME = 50
PAYPAL_OUTAGE_FAILURES = 40
PAYPAL_HISTORY_WEEKS = (1, 2, 3)

GENERATED = "generated by this demo; not real provider traffic"
SIMULATED = "simulated execution: no provider or customer action took place"
ESTIMATED = "risk-weighted counterfactual estimate under explicit assumptions, not observed money"


def _target_database(raw_url: str):
    from src.infrastructure.db_safety import UnsafeDatabaseError, assert_disposable_test_target

    try:
        return assert_disposable_test_target(raw_url), "disposable test database"
    except UnsafeDatabaseError as exc:
        raise SystemExit(f"Refusing to run the demo: {exc}")


# --- webhook bodies ---------------------------------------------------------------------------------

def _razorpay_webhook(event, payment_id, created_at, *, method="card", currency="INR",
                      amount=AMOUNT_MINOR_UNITS, failed=False) -> bytes:
    entity = {
        "id": payment_id, "entity": "payment", "amount": amount, "currency": currency,
        "status": event.split(".", 1)[1], "order_id": f"order_{payment_id[4:]}", "method": method,
        "created_at": created_at,
    }
    if method == "upi":
        entity["vpa"] = "buyer@okdemo"
    if failed:
        entity.update({
            "error_code": "BAD_REQUEST_ERROR", "error_description": "Payment failed",
            "error_source": "bank", "error_step": "payment_authorization", "error_reason": "payment_failed",
        })
    body = {
        "entity": "event", "account_id": "acc_DemoAccount01", "event": event, "contains": ["payment"],
        "payload": {"payment": {"entity": entity}}, "created_at": created_at,
    }
    return json.dumps(body, sort_keys=True).encode()


def _paypal_envelope(webhook_id, event_type, resource_type, resource, at):
    return json.dumps({
        "id": webhook_id, "event_version": "1.0", "create_time": at.strftime("%Y-%m-%dT%H:%M:%SZ"),
        "resource_type": resource_type, "resource_version": "2.0", "event_type": event_type,
        "summary": "Demo-generated sandbox-style event", "resource": resource, "links": [],
    }).encode()


def _paypal_capture(webhook_id, capture_id, order_id, at, *, declined, value="500.00", currency="USD"):
    resource = {
        "id": capture_id, "status": "DECLINED" if declined else "COMPLETED",
        "amount": {"value": value, "currency_code": currency}, "final_capture": True,
        "supplementary_data": {"related_ids": {"order_id": order_id}},
        "create_time": at.strftime("%Y-%m-%dT%H:%M:%SZ"), "update_time": at.strftime("%Y-%m-%dT%H:%M:%SZ"), "links": [],
    }
    if declined:
        resource["status_details"] = {"reason": "DECLINED_BY_RISK_FRAUD_FILTERS"}
    event_type = "PAYMENT.CAPTURE.DECLINED" if declined else "PAYMENT.CAPTURE.COMPLETED"
    return _paypal_envelope(webhook_id, event_type, "capture", resource, at)


def _paypal_approval(webhook_id, order_id, at, *, value="500.00", currency="USD"):
    resource = {
        "id": order_id, "intent": "CAPTURE", "status": "APPROVED",
        "purchase_units": [{"reference_id": "default", "amount": {"value": value, "currency_code": currency}}],
        "create_time": at.strftime("%Y-%m-%dT%H:%M:%SZ"), "links": [],
    }
    return _paypal_envelope(webhook_id, "CHECKOUT.ORDER.APPROVED", "checkout-order", resource, at)


class _Demo:
    def __init__(self, client, secret, run_id):
        self.client, self.secret, self.run_id = client, secret, run_id

    async def razorpay(self, body: bytes, source_event_id: str) -> dict:
        signature = hmac.new(self.secret.encode(), body, hashlib.sha256).hexdigest()
        response = await self.client.post(
            "/ingest/razorpay", content=body,
            headers={"Content-Type": "application/json", "X-Razorpay-Signature": signature,
                     "X-Razorpay-Event-Id": source_event_id},
        )
        if response.status_code != 200:
            raise SystemExit(f"Razorpay webhook {source_event_id} was rejected: HTTP {response.status_code} {response.text}")
        return response.json()

    async def paypal(self, body: bytes) -> dict:
        response = await self.client.post("/webhooks/paypal", content=body, headers={"Content-Type": "application/json"})
        if response.status_code != 200:
            raise SystemExit(f"PayPal webhook was rejected: HTTP {response.status_code} {response.text}")
        return response.json()


