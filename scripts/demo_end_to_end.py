"""
Reproducible end-to-end demonstration of Stages 1-8, driven through the real webhook routes.

Five scenarios run in one database, in this order (every stage decides on its own; nothing is forced):
1. healthy_baseline: healthy Razorpay UPI traffic, then a UPI authorization. Expected: a low predicted
   risk and NO_ACTION.
2. razorpay_card_outage: generated card-outage context (baselines + synthetic traffic, Stages 2-4) and an
   outage burst of Razorpay card webhooks; a card payment is authorized and captured. Expected: a CRITICAL
   episode, RCA on PAYMENT_METHOD=card, ACT on the diagnosis-backed DEGRADATION_CIRCUIT_BYPASS (simulated:
   no provider implements it), an observed capture and a risk-weighted attribution estimate.
3. payment_method_switch: a USD card payment during the same outage, for a merchant without a circuit
   bypass (RECOVERY_DISABLED_ROUTES=DEGRADATION_CIRCUIT_BYPASS for this scenario only). Expected: ACT on
   PROMPT_PAYMENT_METHOD_SWITCH. With PAYPAL_RECOVERY_EXECUTION_ENABLED=true and sandbox credentials, a
   real PayPal sandbox checkout is created and offered (approval needs a sandbox buyer and webhooks a public
   URL, see docs/PAYPAL_SANDBOX_SETUP.md); otherwise the labelled simulator runs and no offer exists.
4. paypal_outage: generated PayPal capture history, then a burst of PayPal capture webhooks (80% declined)
   and an approved PayPal order. Expected: PayPal-scope episodes, SYSTEMIC RCA, ACT on RETRY_SECONDARY_GATEWAY
   (simulated), and no effect on the Razorpay scope. These PayPal events are generated by the demo, so
   PayPal webhook signature verification is replaced in-process for this scenario and the report says so.
5. duplicates: a Razorpay webhook and a PayPal webhook are delivered again. Expected: no new pipeline run,
   prediction, decision or command.

The report labels every result as generated, real (this system's own processing), simulated, estimated or
PayPal-verified. No PayPal payment is fabricated: verified recovered money appears only after PayPal's own
webhooks report a sandbox capture.

Database safety: DATABASE_URL must name the disposable test database exactly (localhost:5434/
payment_recovery_test); every other database, including development and demo databases, is refused.
The schema must already be at Alembic head. --reset truncates application tables first, only after the
server confirms the database name.

Usage:
    DATABASE_URL=postgresql+asyncpg://postgres:password@localhost:5434/payment_recovery_test \\
        python -m scripts.demo_end_to_end --reset
"""
import argparse
import asyncio
