async def _attempt_report(session, attempt_id):
    from sqlalchemy import select

    from src.infrastructure.models import (
        CounterfactualAttributionModel, FailurePredictionModel, InterventionCommandModel, InterventionDecisionModel,
        InterventionExecutionAttemptModel, PaymentMethodSwitchOfferModel, PaymentOutcomeObservationModel,
    )

    async def latest(model, *conditions, order):
        return (await session.execute(select(model).where(*conditions).order_by(order.desc()).limit(1))).scalar_one_or_none()

    prediction = await latest(FailurePredictionModel, FailurePredictionModel.payment_attempt_id == attempt_id,
                              order=FailurePredictionModel.prediction_version)
    decision = await latest(InterventionDecisionModel, InterventionDecisionModel.payment_attempt_id == attempt_id,
                            order=InterventionDecisionModel.decision_version)
    command = await latest(InterventionCommandModel, InterventionCommandModel.payment_attempt_id == attempt_id,
                           order=InterventionCommandModel.created_at)
    execution = observation = attribution = offer = None
    if command is not None:
        execution = await latest(InterventionExecutionAttemptModel, InterventionExecutionAttemptModel.command_id == command.command_id,
                                 order=InterventionExecutionAttemptModel.attempt_number)
        observation = await latest(PaymentOutcomeObservationModel, PaymentOutcomeObservationModel.command_id == command.command_id,
                                   order=PaymentOutcomeObservationModel.observation_version)
        attribution = await latest(CounterfactualAttributionModel, CounterfactualAttributionModel.command_id == command.command_id,
                                   order=CounterfactualAttributionModel.attribution_version)
        offer = (await session.execute(
            select(PaymentMethodSwitchOfferModel).where(PaymentMethodSwitchOfferModel.command_id == command.command_id)
        )).scalar_one_or_none()
    upstream = (decision.evaluation_audit_payload or {}).get("upstream_context", {}) if decision else {}
    return {
        "payment_attempt_id": attempt_id,
        "prediction": None if prediction is None else {
            "status": prediction.prediction_status, "failure_probability": prediction.failure_probability,
            "model": f"{prediction.model_name} {prediction.model_version}",
            "provenance": "heuristic, not validated on real outcomes" if prediction.model_name == "DeterministicBaselineModel" else "artifact",
            "in_active_degradation": (prediction.feature_snapshot or {}).get("is_in_active_degradation"),
        },
        "decision": None if decision is None else {
            "type": decision.decision_type, "route": decision.selected_route_id, "gate_verdict": decision.gate_verdict,
            "policy": f"{decision.policy_id} {decision.policy_version}",
            "diagnosis": {k: upstream.get(k) for k in ("rca_classification", "rca_candidate_dimension", "rca_candidate_value", "rca_evidence_strength")},
        },
        "execution": None if execution is None else {
            "status": execution.execution_status, "executor": execution.executor_name, "is_simulation": execution.is_simulation,
            "provenance": SIMULATED if execution.is_simulation else "real PayPal sandbox call",
        },
        "switch_offer": None if offer is None else {
            "offer_id": str(offer.offer_id), "status": offer.status, "checkout_order_id": offer.checkout_order_id,
            "approve_url": offer.approve_url if offer.status == "OFFERED" else None,
            "expires_at": offer.expires_at.isoformat(),
        },
        "outcome": None if observation is None else {
            "observed": observation.payment_outcome, "terminal_event_type": observation.terminal_event_type,
            "recovered_via_recovery_order": bool((observation.observation_audit_payload or {}).get("recovery", {}).get("recovered_via_recovery_order")),
        },
        "revenue_impact": None if attribution is None else {
            "status": attribution.attribution_status,
            "protected_gmv_minor_units": attribution.attributed_protected_gmv_minor_units,
            "is_simulated_execution": attribution.is_simulated_execution,
            "meaning": ESTIMATED,
        },
    }


async def _scope_episodes(session):
    from sqlalchemy import select

    from src.infrastructure.models import DegradationEpisodeModel, RCAEvaluationModel

    episodes = (await session.execute(
        select(DegradationEpisodeModel).where(DegradationEpisodeModel.status == "ACTIVE")
    )).scalars().all()
    result = {}
    for e in episodes:
        rca = (await session.execute(
            select(RCAEvaluationModel).where(RCAEvaluationModel.episode_id == e.episode_id)
            .order_by(RCAEvaluationModel.evaluation_version.desc()).limit(1)
        )).scalar_one_or_none()
        result.setdefault(e.provider_scope, []).append({
            "segment": f"{e.segment_dimension}={e.segment_value}", "severity": e.severity,
            "peak_absolute_drop": round(e.peak_absolute_drop, 4), "rca": rca.classification if rca else None,
        })
    return result


# --- scenarios -------------------------------------------------------------------------------------

async def _healthy_baseline(demo, now):
    for i in range(HEALTHY_PAYMENTS):
        at = int((now - timedelta(minutes=55) + timedelta(seconds=20 * i)).timestamp())
        pid = f"pay_DemoOk{demo.run_id}{i:03d}"
        await demo.razorpay(_razorpay_webhook("payment.captured", pid, at, method="upi"), f"evt_demo_ok_{demo.run_id}_{i:03d}")
    target = f"pay_DemoHealthy{demo.run_id}"
    await demo.razorpay(_razorpay_webhook("payment.authorized", target, int(now.timestamp()), method="upi"),
                        f"evt_demo_healthy_auth_{demo.run_id}")
    return target


async def _razorpay_outage(demo, now, windows):
    from scripts.generate_live_context import (
        run_stage2_analytics, run_stage3_degradation, run_stage4_rca, seed_historical_baselines,
        seed_upstream_synthetic_traffic,
    )
    from src.infrastructure.database import AsyncSessionLocal

    async with AsyncSessionLocal() as session:
        await seed_historical_baselines(session, windows, "card", now)
        await seed_upstream_synthetic_traffic(session, windows, "card", "INR", 42)
        await run_stage2_analytics(session, windows)
        active = await run_stage3_degradation(session, windows)
        await run_stage4_rca(session, active, "card")

    failed_count = int(OUTAGE_PAYMENTS * OUTAGE_FAILURE_SHARE)
    for i in range(OUTAGE_PAYMENTS):
        at = int((now - timedelta(minutes=20) + timedelta(seconds=15 * i)).timestamp())
        failed = i < failed_count
        event = "payment.failed" if failed else "payment.captured"
        await demo.razorpay(_razorpay_webhook(event, f"pay_Demo{demo.run_id}{i:03d}", at, failed=failed),
                            f"evt_demo_{demo.run_id}_{i:03d}")

    target = f"pay_DemoTarget{demo.run_id}"
    await demo.razorpay(_razorpay_webhook("payment.authorized", target, int(now.timestamp())), f"evt_demo_auth_{demo.run_id}")
    capture_body = _razorpay_webhook("payment.captured", target, int(now.timestamp()) + CAPTURE_DELAY_SECONDS)
    capture_id = f"evt_demo_capture_{demo.run_id}"
    await demo.razorpay(capture_body, capture_id)
    return target, failed_count, (capture_body, capture_id)


async def _payment_method_switch(demo, now):
    from src.core.intervention.policy import DISABLED_ROUTES_ENV

    target = f"pay_DemoSwitch{demo.run_id}"
    previous = os.environ.get(DISABLED_ROUTES_ENV)
    os.environ[DISABLED_ROUTES_ENV] = "DEGRADATION_CIRCUIT_BYPASS"
    try:
        await demo.razorpay(
            _razorpay_webhook("payment.authorized", target, int(now.timestamp()) + 5, currency="USD", amount=SWITCH_AMOUNT_MINOR_UNITS),
            f"evt_demo_switch_auth_{demo.run_id}",
        )
    finally:
        if previous is None:
            os.environ.pop(DISABLED_ROUTES_ENV, None)
        else:
            os.environ[DISABLED_ROUTES_ENV] = previous
    return target


async def _paypal_outage(demo, now, windows):
    from src.core.analytics.service import PaymentHealthAnalyticsService
    from src.infrastructure.analytics_repository import AnalyticsRepository
    from src.infrastructure.database import AsyncSessionLocal
    from src.infrastructure.models import PaymentEventModel

    # Generated PayPal capture history in the same windows of earlier weeks, turned into PayPal-scope
    # baselines by the real Stage 2 service.
    async with AsyncSessionLocal() as session:
        rows = []
        for week in PAYPAL_HISTORY_WEEKS:
            for w_index, (w_start, _) in enumerate(windows):
                start = w_start - timedelta(weeks=week)
                failures = 1 + (week + w_index) % 3
                for i in range(PAYPAL_WINDOW_VOLUME):
                    failed = i < failures
                    rows.append(PaymentEventModel(
                        event_id=uuid.uuid4(), source_system="paypal",
                        source_event_id=f"WH-DEMO-HIST-{demo.run_id}-{week}-{w_index}-{i:02d}",
                        payment_id=f"DEMOHIST{demo.run_id.upper()}{week}{w_index}{i:02d}",
                        order_id=f"DEMOHISTORD{demo.run_id.upper()}{week}{w_index}{i:02d}",
                        timestamp=start + timedelta(seconds=5 * i + 1),
                        event_type="payment.failed" if failed else "payment.captured", currency="USD",
                        amount_minor_units=50000, payment_status="declined" if failed else "completed",
                        error_reason="DECLINED_BY_RISK_FRAUD_FILTERS" if failed else None,
                        ingested_at=start + timedelta(seconds=5 * i + 2),
                    ))
        session.add_all(rows)
        await session.commit()
        analytics = PaymentHealthAnalyticsService(AnalyticsRepository(session))
        for week in sorted(PAYPAL_HISTORY_WEEKS, reverse=True):
            for w_start, w_end in windows:
                await analytics.calculate_and_save_window(w_start - timedelta(weeks=week), w_end - timedelta(weeks=week), "paypal")
        await session.commit()

    for w_index, (w_start, _) in enumerate(windows):
        for i in range(PAYPAL_WINDOW_VOLUME):
            at = w_start + timedelta(seconds=5 * i + 1)
            token = f"{demo.run_id.upper()}{w_index}{i:02d}"
            await demo.paypal(_paypal_capture(
                f"WH-DEMO-OUTAGE-{token}", f"DEMOCAP{token}", f"DEMOORD{token}", at, declined=i < PAYPAL_OUTAGE_FAILURES,
            ))
    order_id = f"DEMOAPPROVED{demo.run_id.upper()}"
    approval_body = _paypal_approval(f"WH-DEMO-APPROVED-{demo.run_id.upper()}", order_id, now)
    await demo.paypal(approval_body)
    return order_id, approval_body


async def run(reset: bool) -> dict:
    from httpx import ASGITransport, AsyncClient
    from sqlalchemy import func, select, text

    from scripts.generate_live_context import compute_tumbling_windows
    from src.api.dependencies import get_paypal_ingestion_service
    from src.core.domain.payment_attempts import paypal_attempt_id
    from src.core.services.paypal_ingestion_service import PayPalIngestionService
    from src.infrastructure.database import AsyncSessionLocal
    from src.infrastructure.db_safety import assert_connected_database, build_truncate_statement
    from src.infrastructure.models import (
        Base, FailurePredictionModel, InterventionCommandModel, InterventionDecisionModel, PipelineRunModel,
    )
    from src.infrastructure.paypal_recovery_executor import recovery_execution_enabled
    from src.infrastructure.repository import SQLIngestionRepository
    from src.main import app

    target, _ = _target_database(os.environ["DATABASE_URL"])
    async with AsyncSessionLocal() as session:
        assert_connected_database((await session.execute(text("SELECT current_database()"))).scalar_one(), target)
        if reset:
            await session.execute(text(build_truncate_statement(Base.metadata)))
            await session.commit()

    now = datetime.now(timezone.utc).replace(microsecond=0)
    run_id = uuid.uuid4().hex[:8]
    _, _, windows = compute_tumbling_windows(now)
    report = {"run_id": run_id, "scenarios": {}}

    async def counts():
        async with AsyncSessionLocal() as session:
            return {
                model.__tablename__: (await session.execute(select(func.count()).select_from(model))).scalar_one()
                for model in (PipelineRunModel, FailurePredictionModel, InterventionDecisionModel, InterventionCommandModel)
            }

    async with AsyncClient(transport=ASGITransport(app=app), base_url="http://demo") as client:
        demo = _Demo(client, os.environ["RAZORPAY_WEBHOOK_SECRET"], run_id)

        healthy = await _healthy_baseline(demo, now)
        async with AsyncSessionLocal() as session:
            report["scenarios"]["1_healthy_baseline"] = {
                "events": f"{HEALTHY_PAYMENTS} captured UPI payments + 1 UPI authorization ({GENERATED})",
                "active_episodes_by_scope": await _scope_episodes(session),
                "target": await _attempt_report(session, healthy),
            }

        outage_target, failed_count, razorpay_duplicate = await _razorpay_outage(demo, now, windows)
        async with AsyncSessionLocal() as session:
            report["scenarios"]["2_razorpay_card_outage"] = {
                "events": f"{OUTAGE_PAYMENTS} card payments, {failed_count} failed, then authorization + capture ({GENERATED}); "
                          "outage context: synthetic traffic and baselines",
                "active_episodes_by_scope": await _scope_episodes(session),
                "target": await _attempt_report(session, outage_target),
            }

        switch_target = await _payment_method_switch(demo, now)
        async with AsyncSessionLocal() as session:
            switch_report = await _attempt_report(session, switch_target)
        switch_report["policy_variant"] = "merchant without a circuit bypass (RECOVERY_DISABLED_ROUTES=DEGRADATION_CIRCUIT_BYPASS)"
        if switch_report["switch_offer"] is None:
            switch_report["why_no_offer"] = (
                "PayPal sandbox execution is not enabled/configured (PAYPAL_RECOVERY_EXECUTION_ENABLED, PAYPAL_CLIENT_ID, "
                "PAYPAL_CLIENT_SECRET); the switch ran on the simulator, so no checkout exists and nothing can be accepted"
                if not recovery_execution_enabled() else "PayPal configuration missing or refused; see logs"
            )
        else:
            switch_report["next_steps"] = (
                "Approve the checkout with a sandbox buyer account; PayPal's webhooks (public URL required) then move the "
                "offer to ACCEPTED, and the merchant's capture to COMPLETED. See docs/PAYPAL_SANDBOX_SETUP.md."
            )
        report["scenarios"]["3_payment_method_switch"] = switch_report

        class _UnverifiedDemoEvents:
            """The demo's own PayPal events carry no PayPal signature; verification is replaced for them only."""

            async def verify_webhook_signature(self, headers, raw_body):
                from types import SimpleNamespace
                return SimpleNamespace(verified=True)

        async def demo_paypal_ingestion():
            async with AsyncSessionLocal() as session:
                yield PayPalIngestionService(SQLIngestionRepository(session), _UnverifiedDemoEvents())

        app.dependency_overrides[get_paypal_ingestion_service] = demo_paypal_ingestion
        try:
            paypal_order, paypal_duplicate = await _paypal_outage(demo, now, windows)
            async with AsyncSessionLocal() as session:
                report["scenarios"]["4_paypal_outage"] = {
                    "events": f"{len(windows) * PAYPAL_WINDOW_VOLUME} PayPal captures, {len(windows) * PAYPAL_OUTAGE_FAILURES} declined, "
                              f"then 1 approved order ({GENERATED}; PayPal signature verification replaced in-process for these events)",
                    "active_episodes_by_scope": await _scope_episodes(session),
                    "target": await _attempt_report(session, paypal_attempt_id(paypal_order)),
                }

            before = await counts()
            razorpay_again = await demo.razorpay(*razorpay_duplicate)
            paypal_again = await demo.paypal(paypal_duplicate)
            after = await counts()
        finally:
            app.dependency_overrides.pop(get_paypal_ingestion_service, None)
        report["scenarios"]["5_duplicates"] = {
            "razorpay_capture_redelivered": razorpay_again.get("status"),
            "paypal_approval_redelivered": paypal_again.get("status"),
            "records_unchanged": before == after,
            "counts": after,
        }

    async with AsyncSessionLocal() as session:
        from src.api.inspection_routes import _verified_recovered_by_currency
        verified = await _verified_recovered_by_currency(session, None)
    report["verified_recovered_payments"] = verified or "none: no PayPal-verified capture through a real recovery yet"
    report["provenance"] = {
        "generated": "every webhook and the outage context/history are generated by this demo",
        "real": "signature-checked ingestion (Razorpay HMAC with a demo secret), Stages 2-8 processing, policy and gates",
        "simulated": "every execution labelled is_simulation=true (SIMULATOR_V1)",
        "estimated": "protected GMV (Stage 8 attribution)",
        "paypal_verified": "only captures PayPal reports for a real sandbox checkout",
    }
    return report


def main() -> int:
    from dotenv import load_dotenv

    load_dotenv()
    parser = argparse.ArgumentParser(description="Run the reproducible Stage 1-8 demonstration.")
    parser.add_argument("--reset", action="store_true", help="truncate application tables first")
    args = parser.parse_args()

    raw_url = os.environ.get("DATABASE_URL", "")
    if not raw_url:
        print("DATABASE_URL is not set; point it at the disposable test database.", file=sys.stderr)
        return 2
    _target_database(raw_url)
    # The demo signs its own webhooks; the secret never leaves this process.
    os.environ["RAZORPAY_WEBHOOK_SECRET"] = f"demo-{secrets.token_hex(16)}"
    os.environ.setdefault("ALLOWED_HOSTS", "demo")
    print(json.dumps(asyncio.run(run(args.reset)), indent=2, default=str))
    return 0


if __name__ == "__main__":
    sys.exit(main())
